-- 005_approvals_triggers_idempotency.sql (Postgres)
--
-- Same tables and columns as the SQLite migration of the same number. Column
-- names are quoted so they keep the camelCase spelling the SQLite schema uses.

CREATE TABLE IF NOT EXISTS pending_approvals (
  id              TEXT   PRIMARY KEY,
  "taskType"      TEXT   NOT NULL,
  payload         TEXT   NOT NULL,
  amount          TEXT   NOT NULL,
  "correlationId" TEXT,
  status          TEXT   NOT NULL,
  "createdAt"     BIGINT NOT NULL,
  "expiresAt"     BIGINT NOT NULL,
  "decidedAt"     BIGINT
);

CREATE TABLE IF NOT EXISTS approval_audit_log (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "approvalId" TEXT   NOT NULL,
  decision     TEXT   NOT NULL,
  ts           BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS triggers (
  id            TEXT    PRIMARY KEY,
  source        TEXT    NOT NULL,
  filter        TEXT    NOT NULL,
  task          TEXT    NOT NULL,
  enabled       BOOLEAN NOT NULL DEFAULT TRUE,
  created_at    TEXT    NOT NULL,
  last_fired_at TEXT
);

CREATE TABLE IF NOT EXISTS trigger_events (
  key      TEXT PRIMARY KEY,
  fired_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS idempotency_keys (
  key           TEXT   PRIMARY KEY,
  "payloadHash" TEXT   NOT NULL,
  "taskType"    TEXT   NOT NULL,
  status        TEXT   NOT NULL,
  result        TEXT   NOT NULL,
  "createdAt"   BIGINT NOT NULL,
  "expiresAt"   BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_idempotency_expires
  ON idempotency_keys ("expiresAt");

ALTER TABLE agent_results ADD COLUMN IF NOT EXISTS "errorType" TEXT;
ALTER TABLE agent_results ADD COLUMN IF NOT EXISTS "durationMs" INTEGER;
